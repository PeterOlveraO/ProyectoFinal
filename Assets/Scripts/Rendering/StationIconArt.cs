        public static Sprite Get(StationIcon icon)
        {
            if (Cache.TryGetValue(icon, out var sprite) && sprite != null) return sprite;
            Color accent = Accent(icon);
            string[] rows = Masks[(int)icon].Split('|');
            var texture = new Texture2D(24, 24, TextureFormat.RGBA32, false)
            { name = "Station_" + icon, filterMode = FilterMode.Point, wrapMode = TextureWrapMode.Clamp };
            var pixels = new Color[24 * 24];
            for (int y = 0; y < 24; y++)
                for (int x = 0; x < 24; x++)
                {
                    int edge = Mathf.Min(x, y, 23 - x, 23 - y);
                    bool cut = (x < 3 || x > 20) && (y < 3 || y > 20);
                    Color color = cut ? Color.clear : edge == 0 ? RetroWorldArt.Ink :
                        edge == 1 ? accent : new Color32(31, 57, 63, 255);
                    if (x >= 4 && x < 20 && y >= 4 && y < 20)
                    {
                        char pixel = rows[19 - y][x - 4];
                        if (pixel == '#') color = accent;
                        if (pixel == '+') color = RetroWorldArt.Cream;
                    }
                    pixels[y * 24 + x] = color;
                }
            texture.SetPixels(pixels);
            texture.Apply(false, true);
            sprite = Sprite.Create(texture, new Rect(0, 0, 24, 24), new Vector2(.5f, .5f),
                32f, 0, SpriteMeshType.FullRect);
            sprite.name = texture.name;
            Cache[icon] = sprite;
            return sprite;
        }

        static Color Accent(StationIcon icon)
        {
            switch (icon)
            {
                case StationIcon.Power: return new Color32(242, 125, 99, 255);
                case StationIcon.Vitality: return new Color32(245, 137, 168, 255);
                case StationIcon.Sprint: return new Color32(114, 210, 228, 255);
                case StationIcon.Armor: return new Color32(180, 158, 231, 255);
                case StationIcon.Acquired: return new Color32(150, 209, 121, 255);
                default: return RetroWorldArt.Gold;
            }
        }
